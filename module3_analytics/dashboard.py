ALL_CATEGORIES = [
    "development_tool",
    "development_server",
    "build_process",
    "background_process",
    "system_or_unknown",
]

def calculate_system_summary(proc_data):
    """
    Compute comprehensive OS workload and resource metrics from snapshot data.

    Returns:
        dict: Aggregated summary statistics including:
          - total_processes: Total process count
          - workload_counts: Process count per category
          - total_rss_mb: Sum of resident memory
          - avg_cpu_percent: Mean CPU utilization
          - top_cpu_proc: Process with highest CPU%
          - top_mem_proc: Process with highest RSS memory
          - state_counts: Distribution across R, S, D, Z, T states
          - priority_counts: Distribution across elevated (<0), default (0), deprioritized (>0)
    """
    processes = proc_data.get("processes", []) if proc_data else []
    total_procs = len(processes)

    workload_counts = {cat: 0 for cat in ALL_CATEGORIES}
    state_counts = {"R": 0, "S": 0, "D": 0, "Z": 0, "Other": 0}
    priority_counts = {"elevated": 0, "standard": 0, "deprioritized": 0}

    total_rss_mb = 0.0
    cpu_sum = 0.0
    cpu_measured_count = 0

    top_cpu_proc = None
    top_mem_proc = None

    for p in processes:
        # Category aggregation
        cat = p.get("workload_category", "system_or_unknown")
        if cat in workload_counts:
            workload_counts[cat] += 1
        else:
            workload_counts["system_or_unknown"] += 1

        # Memory aggregation
        mem = p.get("memory_mb")
        if mem is not None and mem >= 0:
            total_rss_mb += mem
            if top_mem_proc is None or mem > (top_mem_proc.get("memory_mb") or 0.0):
                top_mem_proc = p

        # CPU aggregation
        cpu = p.get("cpu_percent")
        if cpu is not None and cpu >= 0:
            cpu_sum += cpu
            cpu_measured_count += 1
            if top_cpu_proc is None or cpu > (top_cpu_proc.get("cpu_percent") or 0.0):
                top_cpu_proc = p

        # Process State distribution
        st = str(p.get("state", "?"))[:1].upper()
        if st in state_counts:
            state_counts[st] += 1
        else:
            state_counts["Other"] += 1

        # Scheduling Priority distribution
        nice = p.get("nice_value", 0)
        if nice < 0:
            priority_counts["elevated"] += 1
        elif nice == 0:
            priority_counts["standard"] += 1
        else:
            priority_counts["deprioritized"] += 1

    avg_cpu = (cpu_sum / cpu_measured_count) if cpu_measured_count > 0 else 0.0

    return {
        "timestamp": proc_data.get("timestamp", "N/A"),
        "interval_sec": proc_data.get("sampling_interval_seconds", 0.0),
        "total_processes": total_procs,
        "workload_counts": workload_counts,
        "total_rss_mb": total_rss_mb,
        "avg_cpu_percent": avg_cpu,
        "top_cpu_proc": top_cpu_proc,
        "top_mem_proc": top_mem_proc,
        "state_counts": state_counts,
        "priority_counts": priority_counts,
    }


def filter_and_sort_processes(processes, sort_by="cpu", filter_cat=None, limit=15):
    """
    Filter and sort processes according to user CLI parameters.

    Args:
        processes (list): List of process dictionaries
        sort_by (str): One of 'cpu', 'memory', 'nice', 'pid'
        filter_cat (str or None): Workload category filter
        limit (int): Maximum entries to retain

    Returns:
        list: Filtered and sorted processes
    """
    filtered = processes
    if filter_cat:
        filtered = [p for p in filtered if p.get("workload_category") == filter_cat]

    # Create shallow copy to avoid mutating original list
    result = list(filtered)

    if sort_by == "cpu":
        result.sort(key=lambda p: (p.get("cpu_percent") if p.get("cpu_percent") is not None else -1.0), reverse=True)
    elif sort_by == "memory":
        result.sort(key=lambda p: (p.get("memory_mb") if p.get("memory_mb") is not None else -1.0), reverse=True)
    elif sort_by == "nice":
        # Ascending nice: lower nice = higher priority at top
        result.sort(key=lambda p: (p.get("nice_value") if p.get("nice_value") is not None else 0))
    elif sort_by == "pid":
        result.sort(key=lambda p: (p.get("pid") or 0))

    if limit is not None and limit > 0:
        return result[:limit]
    return result


def correlate_governor_actions(actions, live_processes):
    """
    Cross-reference governor history logs with live process table.

    Demonstrates scheduling verification:
    Did the priority change requested by Module 2 actually take effect in
    the Linux OS process table?

    Returns:
        list of dicts with:
          - action: original record
          - live_process: process dict if currently alive, else None
          - sync_status: 'APPLIED', 'PENDING', or 'EXITED'
    """
    live_map = {p.get("pid"): p for p in live_processes if "pid" in p}
    correlated = []

    for act in actions:
        pid = act.get("pid")
        resulting_nice = act.get("resulting_nice")
        action_type = act.get("action_type", "").lower()
        status = act.get("status", "").lower()

        live_proc = live_map.get(pid)
        sync_status = "UNKNOWN"

        if live_proc is None:
            sync_status = "EXITED"
        else:
            live_nice = live_proc.get("nice_value")
            if action_type == "set_nice" and status == "success":
                if live_nice == resulting_nice:
                    sync_status = "APPLIED"
                else:
                    sync_status = "PENDING"
            elif action_type == "evaluate":
                sync_status = "RECOMMENDED"
            else:
                sync_status = "OBSERVED"

        correlated.append({
            "action": act,
            "live_proc": live_proc,
            "sync_status": sync_status,
        })

    return correlated


