def parse_arguments(argv=None):
    """Parse and validate command line arguments."""
    parser = argparse.ArgumentParser(
        description="DevGovernor — Terminal Analytics Dashboard (Module 3)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Standard single-shot dashboard view
  python module3_analytics/dashboard.py --input data/processes.json --history data/actions.jsonl

  # Sort by memory and filter only build processes
  python module3_analytics/dashboard.py --sort memory --filter build_process

  # Live continuous watch mode with 1-second refresh
  python module3_analytics/dashboard.py --watch --refresh-sec 1.0

  # Export snapshot markdown report for OS lab project submission
  python module3_analytics/dashboard.py --export-report docs/dashboard_report.md
        """
    )

    parser.add_argument(
        "--input",
        default="data/processes.json",
        help="Path to monitor output JSON (default: data/processes.json)"
    )
    parser.add_argument(
        "--history",
        default="data/actions.jsonl",
        help="Path to governor actions JSON-lines audit file (default: data/actions.jsonl)"
    )
    parser.add_argument(
        "--sort",
        choices=["cpu", "memory", "nice", "pid"],
        default="cpu",
        help="Sort active process table by column (default: cpu)"
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=15,
        help="Max number of process entries to display (default: 15)"
    )
    parser.add_argument(
        "--filter",
        choices=ALL_CATEGORIES,
        default=None,
        help="Filter process table by workload category"
    )
    parser.add_argument(
        "--watch",
        action="store_true",
        help="Run continuously in watch/auto-refresh mode"
    )
    parser.add_argument(
        "--refresh-sec",
        type=float,
        default=2.0,
        help="Refresh interval in seconds when --watch is active (default: 2.0)"
    )
    parser.add_argument(
        "--export-report",
        metavar="FILE.md",
        default=None,
        help="Generate and export a comprehensive Markdown snapshot report to the specified file"
    )
    parser.add_argument(
        "--no-clear",
        action="store_true",
        help="Disable ANSI terminal clear sequence (useful for CI and piped output)"
    )
    parser.add_argument(
        "--ascii",
        action="store_true",
        help="Use 7-bit ASCII characters instead of Unicode blocks/borders"
    )

    return parser.parse_args(argv)


def main():
    """Main dashboard execution loop."""
    args = parse_arguments()

    # If --export-report was requested directly, load data, export, and exit
    if args.export_report:
        proc_data, err = load_process_data(args.input)
        actions, _ = load_action_history(args.history)
        if err:
            print(f"[Error] Cannot export report: {err}", file=sys.stderr)
            sys.exit(1)

        ok = export_markdown_report(
            proc_data, actions, args.export_report,
            sort_by=args.sort, filter_cat=args.filter
        )
        if ok:
            print(f"[Success] Exported DevGovernor report to '{args.export_report}'.")
            sys.exit(0)
        else:
            sys.exit(1)

    # Standard dashboard loop
    try:
        while True:
            proc_data, err = load_process_data(args.input)
            actions, hist_warn = load_action_history(args.history)

            if err:
                if not args.no_clear:
                    print("\033[2J\033[H", end="")
                print("=" * 84)
                print("      DevGovernor — Linux Developer Productivity & Scheduling Governor")
                print("=" * 84)
                print(f"\n[Awaiting Data / Ingestion Warning]\n{err}\n")
                print(f"Target Input Path : {os.path.abspath(args.input)}")
                print(f"Target History    : {os.path.abspath(args.history)}")
                print("\nTo launch Module 1 in Linux/WSL:")
                print(f"  ./module1_monitor/monitor --output {args.input} --interval 1\n")
                print("To run with pre-packaged demonstration data:")
                print("  python module3_analytics/dashboard.py --input data/processes.sample.json "
                      "--history data/actions.sample.jsonl\n")
                if actions:
                    print(f"Loaded {len(actions)} Governor Action(s) from History:")
                    for a in actions[-3:]:
                        print(f"  - {a.get('timestamp')} PID {a.get('pid')}: "
                              f"{a.get('action_type')} -> {a.get('status')}")
                print("=" * 84)
            else:
                render_dashboard(
                    proc_data,
                    actions,
                    sort_by=args.sort,
                    limit=args.limit,
                    filter_cat=args.filter,
                    clear_screen=(not args.no_clear),
                    ascii_only=args.ascii,
                )

            if not args.watch:
                break

            time.sleep(max(0.2, args.refresh_sec))

    except KeyboardInterrupt:
        print("\n[DevGovernor Dashboard] Stopped cleanly.")
        sys.exit(0)


if __name__ == "__main__":
    main()
