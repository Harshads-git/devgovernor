def render_progress_bar(percent, width=10, ascii_only=False):
    """
    Generate an ASCII or Unicode visual resource gauge bar.

    Examples:
      Unicode: [████░░░░░░] 40.0%
      ASCII:   [====......] 40.0%
      Null:    [   null   ]

    Args:
        percent (float or None): Value between 0.0 and 100.0+
        width (int): Character width of the inner bar
        ascii_only (bool): If True, use standard ASCII characters

    Returns:
        str: Formatted progress bar with percentage
    """
    if percent is None or percent < 0:
        return f"[{'null':^{width}}] --.-%"

    # Clamp effective percentage for bar filling (handle >100% multi-core)
    effective_pct = max(0.0, min(100.0, percent))
    filled_len = int(round(width * (effective_pct / 100.0)))

    if ascii_only:
        fill_char = "="
        empty_char = "."
    else:
        fill_char = "█"
        empty_char = "░"

    bar = (fill_char * filled_len) + (empty_char * (width - filled_len))
    overflow_marker = "+" if percent > 100.0 else " "

    return f"[{bar}]{overflow_marker}{percent:5.1f}%"


def format_category_badge(category):
    """Format workload categories into neat fixed-width badges."""
    badges = {
        "development_tool": "[DEV-TOOL]",
        "development_server": "[DEV-SRV ]",
        "build_process": "[BUILD   ]",
        "background_process": "[BG-PROC ]",
        "system_or_unknown": "[SYS/UNK ]",
    }
    return badges.get(category, f"[{str(category)[:8]:<8}]")


def format_state_label(state):
    """
    Translate single-letter OS process states into human-readable descriptions.
    Illustrates Linux Process State Machine for viva.
    """
    states = {
        "R": "R (Running/Runnable)",
        "S": "S (Interruptible Sleep)",
        "D": "D (Disk/Uninterruptible)",
        "Z": "Z (Zombie/Defunct)",
        "T": "T (Stopped/Traced)",
        "I": "I (Idle Kernel Thread)",
    }
    return states.get(str(state).upper(), f"{state} (Unknown)")


