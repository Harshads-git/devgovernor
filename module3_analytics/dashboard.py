def render_dashboard(proc_data, actions, sort_by="cpu", limit=15, filter_cat=None,
                     clear_screen=True, ascii_only=False):
    """
    Render terminal dashboard presentation view.
    """
    if clear_screen:
        # Cross-platform ANSI terminal clear + home cursor
        print("\033[2J\033[H", end="")

    line_char = "=" if ascii_only else "═"
    subline_char = "-" if ascii_only else "─"
    box_w = 88

    # 1. Header Banner
    print(line_char * box_w)
    print("      DevGovernor — Linux Developer Productivity & Scheduling Governor")
    print("      Module 3: Terminal Analytics & Scheduling Priority Dashboard")
    print(line_char * box_w)

    # 2. System Summary Cards
    summary = calculate_system_summary(proc_data)
    ts = summary["timestamp"]
    interval = summary["interval_sec"]
    total_procs = summary["total_processes"]
    total_rss = summary["total_rss_mb"]
    avg_cpu = summary["avg_cpu_percent"]

    print(f"  Snapshot Time : {ts} (UTC)    Sampling Interval: {interval:.1f}s")
    print(f"  Monitored PIDs: {total_procs:<6} Total Tracked RSS: {total_rss:.1f} MB ({total_rss / 1024:.2f} GB)")
    print(f"  Mean CPU Load : {avg_cpu:.1f}%    System Contention: "
          f"{'HIGH' if avg_cpu > 75.0 else 'MODERATE' if avg_cpu > 30.0 else 'NOMINAL'}")
    print(subline_char * box_w)

    # Workload Distribution Badges
    wk_counts = summary["workload_counts"]
    breakdown_parts = [
        f"{format_category_badge(k)}: {wk_counts.get(k, 0)}"
        for k in ALL_CATEGORIES
    ]
    print(f"  Workload Categories : {' | '.join(breakdown_parts[:3])}")
    print(f"                        {' | '.join(breakdown_parts[3:])}")

    # Process State & Priority distribution
    st = summary["state_counts"]
    pr = summary["priority_counts"]
    print(f"  Process States      : Running (R): {st['R']} | Sleeping (S): {st['S']} | "
          f"Disk Sleep (D): {st['D']} | Zombie (Z): {st['Z']}")
    print(f"  Scheduling Balance  : Elevated (<0): {pr['elevated']} | "
          f"Standard (0): {pr['standard']} | Deprioritized (>0): {pr['deprioritized']}")

    if summary["top_cpu_proc"]:
        tcp = summary["top_cpu_proc"]
        print(f"  Top CPU Consumer    : PID {tcp.get('pid')} ({tcp.get('name')}) at {tcp.get('cpu_percent', 0.0):.1f}% CPU")
    if summary["top_mem_proc"]:
        tmp = summary["top_mem_proc"]
        print(f"  Top Memory Consumer : PID {tmp.get('pid')} ({tmp.get('name')}) at {tmp.get('memory_mb', 0.0):.1f} MB RSS")

    print(line_char * box_w)

    # 3. Filtered & Sorted Process Table
    processes = proc_data.get("processes", []) if proc_data else []
    display_procs = filter_and_sort_processes(processes, sort_by=sort_by, filter_cat=filter_cat, limit=limit)

    filter_info = f" [Filter: {filter_cat}]" if filter_cat else " [Filter: NONE]"
    print(f"  Active Process Table (Sorted by: {sort_by.upper()}{filter_info}, Showing Top {len(display_procs)} of {total_procs}):")

    # Table Header
    header = (
        f"  {'PID':>6} {'PPID':>6} {'NAME':<15} {'CATEGORY':<12} {'ST':<3} "
        f"{'NICE':>5}  {'CPU % GAUGE':<19}  {'RSS MEM (MB)':>12}"
    )
    print(header)
    print("  " + subline_char * (box_w - 4))

    if not display_procs:
        print("    [No processes matched current filter criteria]")
    else:
        for p in display_procs:
            pid = p.get("pid", 0)
            ppid = p.get("ppid", 0)
            name = str(p.get("name", "unknown"))[:14]
            cat = format_category_badge(p.get("workload_category", ""))
            state = str(p.get("state", "?"))[:2]
            nice = p.get("nice_value", 0)

            cpu = p.get("cpu_percent")
            cpu_gauge = render_progress_bar(cpu, width=8, ascii_only=ascii_only)

            mem = p.get("memory_mb")
            mem_str = f"{mem:8.1f} MB" if mem is not None else "     null MB"

            row = (
                f"  {pid:>6} {ppid:>6} {name:<15} {cat:<12} {state:<3} "
                f"{nice:>5}  {cpu_gauge:<19}  {mem_str:>12}"
            )
            print(row)

    print("  " + subline_char * (box_w - 4))

    # 4. Governor Action History & Before/After Audit
    print("  Recent Governor Actions & Scheduling Verification Audit:")
    if not actions:
        print("    [No governor actions logged yet. Run module2_governor to evaluate or adjust priorities.]")
    else:
        correlated = correlate_governor_actions(actions, processes)
        # Show up to last 5 actions
        for item in reversed(correlated[-5:]):
            act = item["action"]
            sync = item["sync_status"]
            ts_act = act.get("timestamp", "N/A")
            pid = act.get("pid", 0)
            pname = act.get("process_name", "unknown")
            act_type = str(act.get("action_type", "")).upper()
            status = str(act.get("status", "")).upper()
            prev_nice = act.get("previous_nice")
            res_nice = act.get("resulting_nice")
            msg = act.get("message", "")

            # Status badges
            sync_tag = f"[{sync}]"
            prev_str = str(prev_nice) if prev_nice is not None else "N/A"
            res_str = str(res_nice) if res_nice is not None else "N/A"

            # Check if live process reflects new nice value
            live_info = ""
            if item["live_proc"] is not None:
                live_nice = item["live_proc"].get("nice_value")
                live_info = f" (Live Nice: {live_nice})"
            else:
                live_info = " (Process Terminated)"

            print(f"    * {ts_act} | PID {pid:<5} ({pname}) | {act_type}:{status} {sync_tag}")
            print(f"      Nice: {prev_str} -> {res_str}{live_info} | {msg}")

    print(line_char * box_w)
    print("  Controls: [Ctrl+C] Quit | Sort: --sort {cpu,memory,nice,pid} | Filter: --filter <cat>")
    print("  Report:   --export-report <file.md> to export a markdown summary for OS lab viva")
    print(line_char * box_w)


