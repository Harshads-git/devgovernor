def load_process_data(filepath, retries=2, retry_delay=0.05):
    """
    Safely load processes JSON snapshot generated by Module 1.

    Zero-crash guarantees:
      - Gracefully handles non-existent files.
      - Gracefully handles zero-byte files (sampled while monitor is booting).
      - Gracefully recovers from malformed/truncated JSON.
      - Retries transient read errors if a write happens simultaneously.

    Args:
        filepath (str): Path to data/processes.json
        retries (int): Number of micro-retries for transient parse errors
        retry_delay (float): Seconds to pause between retries

    Returns:
        tuple: (dict_data or None, error_string or None)
    """
    if not os.path.exists(filepath):
        return None, (
            f"Snapshot file '{filepath}' not found.\n"
            f"Start module1_monitor to generate live data, e.g.:\n"
            f"  ./module1_monitor/monitor --output {filepath} --interval 1\n"
            f"Or test using sample data:\n"
            f"  python module3_analytics/dashboard.py --input data/processes.sample.json "
            f"--history data/actions.sample.jsonl"
        )

    for attempt in range(retries + 1):
        try:
            # Check for empty file
            if os.path.getsize(filepath) == 0:
                if attempt < retries:
                    time.sleep(retry_delay)
                    continue
                return None, f"Snapshot file '{filepath}' is currently empty (sampling in progress)."

            with open(filepath, "r", encoding="utf-8", errors="replace") as f:
                data = json.load(f)

            # Schema sanity validation
            if not isinstance(data, dict):
                return None, f"Invalid format in '{filepath}': root element must be a JSON object."

            if "processes" not in data or not isinstance(data["processes"], list):
                return None, f"Invalid format in '{filepath}': missing 'processes' list."

            return data, None

        except json.JSONDecodeError as err:
            if attempt < retries:
                time.sleep(retry_delay)
                continue
            return None, f"Malformed JSON in '{filepath}' (line {err.lineno}, col {err.colno}): {err.msg}"
        except PermissionError:
            return None, f"Permission denied reading '{filepath}'."
        except Exception as err:
            return None, f"Unexpected error reading '{filepath}': {err}"

    return None, f"Failed to read '{filepath}' after {retries} retries."


def load_action_history(filepath, max_records=15):
    """
    Safely load governor action records from a JSON-lines file.

    Zero-crash guarantees:
      - Missing file returns empty list without failing.
      - Corrupt/incomplete lines are skipped gracefully.
      - Retains the most recent `max_records`.

    Args:
        filepath (str): Path to data/actions.jsonl
        max_records (int): Maximum recent records to return

    Returns:
        tuple: (list_of_records, warning_string_or_None)
    """
    if not os.path.exists(filepath):
        return [], None

    records = []
    skipped_lines = 0

    try:
        with open(filepath, "r", encoding="utf-8", errors="replace") as f:
            for line_no, raw_line in enumerate(f, start=1):
                line = raw_line.strip()
                if not line:
                    continue
                try:
                    record = json.loads(line)
                    if isinstance(record, dict):
                        records.append(record)
                    else:
                        skipped_lines += 1
                except json.JSONDecodeError:
                    skipped_lines += 1
                    continue

        return records[-max_records:], None

    except PermissionError:
        return [], f"Permission denied reading '{filepath}'."
    except Exception as err:
        return [], f"Error reading action history '{filepath}': {err}"


